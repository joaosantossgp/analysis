# build_desktop.ps1
# Gera a pasta distribuível dist/CVMAnalytics/ com CVMAnalytics.exe.
#
# Uso:
#   .\desktop\build_desktop.ps1
#   .\desktop\build_desktop.ps1 -SkipViteBuild   # reutiliza dist/ existente
#   .\desktop\build_desktop.ps1 -Version 0.2.0   # versao explícita (default: git describe --tags --always)
#   .\desktop\build_desktop.ps1 -Verbose
#
# Saída:
#   dist/CVMAnalytics/CVMAnalytics.exe   — clique para abrir o app
#
# Requisitos:
#   - Python com pyinstaller, pywebview instalados  (pip install -r requirements.txt)
#   - Node.js + npm instalados apenas para compilar apps/desktop-web

param(
    [switch]$SkipViteBuild,
    [switch]$Verbose,
    [string]$Version = ""
)

$ErrorActionPreference = "Stop"
$Root    = Split-Path $PSScriptRoot -Parent
$ViteDir = Join-Path $Root "apps\desktop-web"
$DesktopDir = $PSScriptRoot

Write-Host ""
Write-Host "=== CVM Analytics Desktop Build ===" -ForegroundColor Cyan
Write-Host "  Root: $Root"
Write-Host ""

# ---------------------------------------------------------------------------
# Passo 1 - Vite static SPA build (apps/desktop-web)
# Produces apps/desktop-web/dist/ which app.spec bundles to _internal/desktop-web/.
# Optional: pass -SkipViteBuild to reuse the prior build.
# ---------------------------------------------------------------------------
if (-not $SkipViteBuild) {
    if (Test-Path (Join-Path $ViteDir "package.json")) {
        Write-Host "[1/3] vite build (apps/desktop-web)..." -ForegroundColor Yellow
        Push-Location $ViteDir
        try {
            if (-not (Test-Path "node_modules")) {
                Write-Host "  installing apps/desktop-web dependencies..." -ForegroundColor Gray
                & npm install
                if ($LASTEXITCODE -ne 0) { throw "npm install (desktop-web) falhou (exit $LASTEXITCODE)" }
            }
            & npm run build
            if ($LASTEXITCODE -ne 0) { throw "vite build falhou (exit $LASTEXITCODE)" }
        } finally {
            Pop-Location
        }
        Write-Host "  OK: apps/desktop-web/dist/ gerado" -ForegroundColor Green
    } else {
        Write-Host "[1/3] apps/desktop-web ausente - pulando vite build" -ForegroundColor Gray
    }
} else {
    Write-Host "[1/3] Pulando vite build (-SkipViteBuild)" -ForegroundColor Gray
}

$ViteIndex = Join-Path $ViteDir "dist\index.html"
if (-not (Test-Path $ViteIndex)) {
    throw "Vite build nao encontrado em $ViteIndex. Rode sem -SkipViteBuild."
}

# ---------------------------------------------------------------------------
# Passo 2 — Injetar versao em desktop/__version__.py
# ---------------------------------------------------------------------------
Write-Host "[2/3] Injetando versao em desktop/__version__.py..." -ForegroundColor Yellow

if (-not $Version) {
    # Full describe: exact tag (v0.2.0) or commits after tag (v0.2.0-5-gabcdef).
    # --abbrev=0 was tag-only and hid post-tag commits from the bundled semver string.
    $gitTag = ""
    $gitDescribeExitCode = 1
    try {
        $gitTag = (git -C $Root describe --tags --always 2>$null)
        $gitDescribeExitCode = $LASTEXITCODE
    } catch {
        $gitTag = ""
        $gitDescribeExitCode = 1
    }
    if ($gitDescribeExitCode -eq 0 -and $gitTag) {
        $Version = $gitTag -replace '^v', ''
    } else {
        $Version = "0.1.0"
    }
}
$VersionPy = Join-Path $DesktopDir "__version__.py"
$VersionContent = "__version__ = `"$Version`""
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($VersionPy, "$VersionContent`n", $Utf8NoBom)
Write-Host "  OK: versao $Version injetada em __version__.py" -ForegroundColor Green

# Build provenance — bundled so the running app can prove which build it is.
# A stale or manually-built artifact whose build_time predates the release tag
# is then visible on the Status page, catching the "shipped exe reports an old
# version" failure class at the source (see desktop/_build_info.py).
$BuildCommit = ""
try {
    $BuildCommit = (git -C $Root rev-parse --short HEAD 2>$null)
    if ($LASTEXITCODE -ne 0) { $BuildCommit = "" }
} catch { $BuildCommit = "" }
$BuildTime = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
$BuildInfoPy = Join-Path $DesktopDir "_build_info.py"
$BuildInfoContent = @"
# Generated by desktop/build_desktop.ps1 at build time. Do not edit by hand.
version = "$Version"
build_commit = "$BuildCommit"
build_time = "$BuildTime"
"@
[System.IO.File]::WriteAllText($BuildInfoPy, "$BuildInfoContent`n", $Utf8NoBom)
Write-Host "  OK: provenance gravada em _build_info.py (commit=$BuildCommit, time=$BuildTime)" -ForegroundColor Green

# ---------------------------------------------------------------------------
# Passo 3 — PyInstaller
# ---------------------------------------------------------------------------
Write-Host "[3/3] PyInstaller bundle..." -ForegroundColor Yellow

$SpecFile = Join-Path $DesktopDir "app.spec"
if (-not (Test-Path $SpecFile)) {
    throw "app.spec nao encontrado em $SpecFile"
}

Push-Location $Root
try {
    $pyArgs = @($SpecFile, "--noconfirm")
    if ($Verbose) { $pyArgs += "--log-level=INFO" }
    pyinstaller @pyArgs
    if ($LASTEXITCODE -ne 0) { throw "PyInstaller falhou (exit $LASTEXITCODE)" }
} finally {
    Pop-Location
}

# ---------------------------------------------------------------------------
# Phase 0 contract: do NOT copy the dev DB into the bundle.
# The packaged app provisions its DB under %USERPROFILE%\Documents\CVMAnalytics\db
# at first launch (see desktop/app.py::_migrate_legacy_db_once). Shipping the
# dev DB into dist/ would either be wasted bytes (user has their own runtime
# DB under Documents) or unsafe (the old auto-updater overwrote user data with
# the bundled DB).
# ---------------------------------------------------------------------------

$DistDir = Join-Path $Root "dist\CVMAnalytics"

# ---------------------------------------------------------------------------
# Resultado
# ---------------------------------------------------------------------------
$ExePath  = Join-Path $Root "dist\CVMAnalytics\CVMAnalytics.exe"

if (Test-Path $ExePath) {
    $SizeMB = [math]::Round((Get-ChildItem $DistDir -Recurse | Measure-Object -Property Length -Sum).Sum / 1MB, 0)
    Write-Host ""
    Write-Host "=== Build concluído ===" -ForegroundColor Green
    Write-Host "  Pasta:  $DistDir"
    Write-Host "  Exe:    $ExePath"
    Write-Host "  Tamanho total: ~$SizeMB MB"
    Write-Host ""
    Write-Host "Para abrir: clique duas vezes em CVMAnalytics.exe" -ForegroundColor Cyan
    Write-Host "Ou via terminal: & '$ExePath'"
} else {
    Write-Host ""
    Write-Host "ERRO: CVMAnalytics.exe nao encontrado em $ExePath" -ForegroundColor Red
    exit 1
}
